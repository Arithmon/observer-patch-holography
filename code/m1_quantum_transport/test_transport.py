def alter(value, path, replacement):
    for part in path[:-1]:
        value = value[part]
    value[path[-1]] = replacement


@pytest.mark.parametrize("path,replacement", MUTATIONS)
def test_semantic_forgery_rejected(evidence, path, replacement):
    bad = copy.deepcopy(evidence)
    alter(bad, path, replacement)
    assert bad != evidence
    with pytest.raises(ValueError, match="independent reconstruction"):
        check.verify_evidence(bad)


