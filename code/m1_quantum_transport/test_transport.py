def test_all_cone_dynamics_against_explicit_error_bound():
    with mp.workdps(45):
        pauli = (mp.matrix([[0, 1], [1, 0]]), mp.matrix([[0, -1j], [1j, 0]]),
                 mp.matrix([[1, 0], [0, -1]]))
        for node, q, k in itertools.product(check.nodes(), (32, 128),
                                           ((1, 2, 3), (-2, 1, 0), (0, 0, 1))):
            a, time = mp.mpf(1)/q, mp.mpf(7)/10
            tick = 3*a
            steps = int(time/tick)
            actual = mp.eye(2)
            for axis in range(3):
                theta = mp.pi*node["index"][axis]/2+a*k[axis]
                actual = (mp.cos(theta)*mp.eye(2)-mp.j*mp.sin(theta)*pauli[axis])*actual
            generator = sum((k[i]*int(node["derivative"][i][i])*pauli[i] for i in range(3)), mp.zeros(2))
            normk = mp.sqrt(sum(x*x for x in k))
            target = mp.cos(time*normk/3)*mp.eye(2)-mp.j*mp.sin(time*normk/3)*generator/normk
            difference = actual**steps-target
            # Frobenius/sqrt(2) equals the operator norm for the difference of SU(2) matrices.
            error = mp.sqrt(sum(abs(x)**2 for x in difference)/2)
            assert error <= (2*time/3)*a*normk**2+a*normk


def test_global_coercivity_on_complete_shifted_grids():
    with mp.workdps(40):
        zeros = [[mp.pi*i/2 for i in node["index"]] for node in check.nodes()]
        for raw in itertools.product(range(7), repeat=3):
            theta = [2*mp.pi*(mp.mpf(i)+mp.mpf(1)/7)/7 for i in raw]
            scalar = mp.fprod(mp.cos(x) for x in theta)+mp.fprod(mp.sin(x) for x in theta)
            epsilon = mp.acos(scalar)
            def distance(zero):
                return mp.sqrt(sum(((x-y+mp.pi) % (2*mp.pi)-mp.pi)**2 for x, y in zip(theta, zero)))
            assert epsilon >= min(map(distance, zeros))/(8*mp.sqrt(3))


